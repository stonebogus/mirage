namespace Mirage.Graphics.Vertices;

/// <summary>
/// Specifies the storage format of a vertex attribute.
/// </summary>
public enum VertexFormat
{
    /// <summary>
    /// One 32-bit floating-point component.
    /// </summary>
    Float,

    /// <summary>
    /// Two 32-bit floating-point components.
    /// </summary>
    Vector2,

    /// <summary>
    /// Three 32-bit floating-point components.
    /// </summary>
    Vector3,

    /// <summary>
    /// Four 32-bit floating-point components.
    /// </summary>
    Vector4,
}
